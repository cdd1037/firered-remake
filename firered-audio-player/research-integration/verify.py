#!/usr/bin/env python3
"""Fail closed on empty/missing/failed renders; report bounded source-loop execution."""
import collections, csv, hashlib, json, pathlib, re
ROOT=pathlib.Path(__file__).resolve().parents[1];P=ROOT/'research-integration'
x=json.loads((P/'inventory.json').read_text());initial=json.loads((P/'render/coverage.json').read_text());loops=json.loads((P/'loop-render/coverage.json').read_text())
sha=lambda p:hashlib.sha256(p.read_bytes()).hexdigest()
expected={s['name']:s for s in x['songs']};loop_expected={n:s for n,s in expected.items() if s['looping']}
assert len(expected)==111 and len(loop_expected)==25
assert {r['name'] for r in initial['rows']}==expected.keys()
assert {r['name'] for r in loops['rows']}==loop_expected.keys()
assert initial['coreAssemblySha256']==loops['coreAssemblySha256']
assert initial['runtimeSourceSha256']==loops['runtimeSourceSha256']==x['runtimeSourceSha256']
reports=[]
for label,coverage,seconds in [('20s',initial,20),('120s',loops,120)]:
 for r in coverage['rows']:
  assert r['status']=='rendered' and r['blockPartitionExact'],(label,r['name'],r)
  for variant in ['first','second']:
   z=r[variant]
   assert z['Error'] is None and z['Nonfinite']==0 and z['Clipped']==0,(label,r['name'],z)
   assert z['CompletedFrames']==seconds*48000 and z['OutputFrames']==seconds*48000
   assert z['Peak']>0 and z['LastNonzeroFrame']>=0
   assert z['Ended']==(not expected[r['name']]['looping']),(label,r['name'],z['Ended'])
for r in loops['rows']:
 name=r['name'];s=expected[name];trace=(P/'loop-render'/(name+'.events.txt')).read_text()
 observed={int(t) for t in re.findall(r'\btrack=(\d+).*\bgoto\b',trace)}
 source={t['index'] for t in s.get('sourceTracks',[]) if t['gotoLines']}
 # Read source if an inventory was freshly generated by the standalone preparation script.
 if not source:
  text=(ROOT.parent/'audio-reference-build/pokefirered'/s['assemblyPath']).read_text();idx=None
  for line in text.splitlines():
   m=re.match(rf'{re.escape(name)}_(\d+):$',line)
   if m:idx=int(m[1])-1
   if re.search(r'\bGOTO\b',line) and idx is not None:source.add(idx)
 assert source and observed==source,(name,source,observed)
 reports.append({'id':s['id'],'sourceLoopTracks':sorted(source),'observedLoopTracks':sorted(observed),'gotoCount':r['first']['Gotos'],'firstGotoOutputFrame':min(map(int,re.findall(r'\bsample=(\d+).*\bgoto\b',trace)))})
for s in x['songs']:
 r=next(r for r in initial['rows'] if r['name']==s['name'])
 s['runtimeAdmission']='bounded-render-verified; host lifecycle, mixing and listening acceptance remain separate'
 s['renderCoverage']={'initialSeconds':20,'blocks':[512,257],'blockPartitionExact':True,'nonzero':True,'finite':True,'clippedSamples':0,'endedAt20Seconds':r['first']['Ended'],'peak':r['first']['Peak'],'pcmSha256':r['first']['Hash']}
 if s['looping']:
  lr=next(r for r in loops['rows'] if r['name']==s['name'])
  s['renderCoverage'].update({'extendedSeconds':120,'allSourceLoopTracksObserved':True,'extendedPcmSha256':lr['first']['Hash']})
(P/'inventory.json').write_text(json.dumps(x,indent=2)+'\n')
summary={'scope':'Frozen baseline synthesis only; no main-game mutations; no full-game, hardware, listening or simultaneous-player equivalence claim.',
 'manifestedIds':143,'normalCriesFromExisting386Catalog':33,'freshlyRenderedManifestedNoncry':110,'additionalRenderedPreviouslyMissingRecorded':['SE_BOO'],'totalCandidates':144,
 'freshNoncryRenders':111,'initialSecondsEach':20,'extendedLoopingCues':25,'extendedSecondsEach':120,'blockSizes':[512,257],
 'actualExceptions':[],'nonfiniteOutputs':0,'clippedSamples':0,'silentCues':0,'blockPartitionExact':True,'all86FiniteCuesEndedBy20Seconds':True,'all25LoopingCuesReachedEverySourceLoopTrackBy120Seconds':True,
 'sourceMetadataMismatches':x['summary']['manifestSourceMismatches'],'observedLoopTracks':reports,
 'runtimeVersion':initial['runtime'],'coreAssemblySha256':initial['coreAssemblySha256'],'coreRuntimeSourceSha256':initial['runtimeSourceSha256'],
 'elapsedSynthesisSeconds':sum(r[k]['ElapsedSeconds'] for d in [initial,loops] for r in d['rows'] for k in ['first','second']),
 'missingInstructionsOrParametersEncountered':[],
 'remainingIntegrationRequirements':['Retain source player IDs 0/1/2/3/4; baseline isolated render uses synth 0 for BGM, 1 for all song-table effects, 2 for cry, and is not a complete concurrent source-player implementation.',
 'Keep all 8 fanfare counters separate from audio Ended: N decrements plus zero-counter completion frame; preserve BGM suspend/resume, cancellation, and token ownership.',
 'Cry catalog admission only mode 0 with fixed normal parameters; source caller pan/stereo variations and special cry modes are not covered.',
 'SE_LOW_HEALTH and SE_M_GUST are looping source effects and require explicit owner cancellation.',
 'SE_BOO still has no recorded fallback in the four main catalogs, despite successful synth rendering.',
 'Unknown IDs/modes/operations must fail explicitly; no silent remapping or success from header reads.'],
 'artifactSha256':{str(p.relative_to(ROOT)):sha(p) for p in [P/'inventory.json',P/'render/coverage.json',P/'loop-render/coverage.json',ROOT/'results/phase5-catalog/coverage.json']}}
(P/'summary.json').write_text(json.dumps(summary,indent=2)+'\n')
fields=['id','category','manifested','manifest','sourceCommit','sourceSymbol','sourcePath','sourcePlayer','priority','sourceCounter','songId','songAddress','songAddressHex','species','cryMode','toneAddress','looping','researchPlayer']
with (P/'integration-inventory.csv').open('w',newline='') as f:
 writer=csv.DictWriter(f,fieldnames=fields,extrasaction='ignore');writer.writeheader();writer.writerows(x['songs']+x['normalCries'])
print(json.dumps({k:v for k,v in summary.items() if k not in ['observedLoopTracks','coreRuntimeSourceSha256','remainingIntegrationRequirements']},indent=2))
