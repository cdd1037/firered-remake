#!/usr/bin/env python3
"""Copy our original core + authenticated private resources into the opt-in local host.
No downloads, SDK copies, ROM runtime dependency or encoded recording fallback.
"""
import hashlib,json,pathlib,shutil,sys,subprocess
ROOT=pathlib.Path(__file__).resolve().parents[1]
GAME=pathlib.Path(sys.argv[1]).resolve() if len(sys.argv)>1 else ROOT.parent/'firered-remake'
inv=json.loads((ROOT/'research-integration/inventory.json').read_text())
coverage=json.loads((ROOT/'research-integration/render/coverage.json').read_text())
rows={r['songAddress']:r for r in coverage['rows']}
assert len(inv['songs'])==111 and len(inv['normalCries'])==33 and len(rows)==111
for cue in inv['songs']:
    r=rows[cue['songAddress']]
    assert r['status']=='rendered' and r['blockPartitionExact']
    for part in ('first','second'):
        assert r[part]['Nonfinite']==r[part]['Clipped']==0 and r[part]['Peak']>0
keys=('id','sourceCommit','sourceSymbol','sourcePath','sourcePlayer','priority','sourceCounter','songAddress','species','looping')
cues=[]
for cue in inv['songs']+inv['normalCries']:
    row={k:cue.get(k,0 if k in ('songAddress','species') else None) for k in keys}
    cues.append(row)
assert len({c['id'] for c in cues})==144
manifest={'schemaVersion':1,'sourceCommit':inv['fixedRevision'],'cues':sorted(cues,key=lambda c:c['id'])}
encoded=(json.dumps(manifest,indent=2)+'\n').encode()
sha=lambda b:hashlib.sha256(b).hexdigest()
data=GAME/'content/generated/synth-audio'; data.mkdir(parents=True,exist_ok=True)
(data/'manifest.json').write_bytes(encoded)
for name,expected in [('firered.pack','00b3a8376e2a44f1919d4a2573a63cb2873a19b5662df496c4f292c16ad0b46d'),('normal-cries.bin','623fe59bb7fc0b8d3907dd67bc677a7985037e0086698636f35db82e113d7f2e')]:
    source=ROOT/'resources'/name
    assert sha(source.read_bytes())==expected
    shutil.copyfile(source,data/name)
core=GAME/'src/Game.Godot/OriginalAudioCore';core.mkdir(exist_ok=True)
names=['Resources.cs','Sequence.cs','Synth.cs','PsgSynth.cs','Profiles.cs','Cry.cs','CryCatalog.cs']
if (ROOT/'src/HostControls.cs').exists():names.append('HostControls.cs')
sourcehashes={}
for name in names:
    source=ROOT/'src'/name
    shutil.copyfile(source,core.parent/("OriginalAudioCore_"+name))
    old=core/name
    if old.exists():old.unlink()
    sourcehashes[name]=sha(source.read_bytes())
(GAME/'src/Game.Godot/SynthManifestIdentity.cs').write_text('''// Generated by the local original-player export tool; fixed admitted resource identity.
internal static class SynthManifestIdentity
{
    public const string Sha256 = "%s";
    public const int Bytes = %d;
    public const int CueCount = 144;
    public const string SourceCommit = "%s";
}
'''%(sha(encoded),len(encoded),inv['fixedRevision']))
record={'scope':'Original C# implementation snapshot; private copyrighted resource pack stays outside source control. Earlier research inspected agbplay; no copied implementation/dependency and no clean-room certification.', 'baselineCommit':'f4fd77c8927334dc3840c5c602cb1abead2152da','sourceCheckpoint':subprocess.check_output(['git','rev-parse','HEAD'],cwd=ROOT,text=True).strip(),'sourceSha256':sourcehashes,'manifestSha256':sha(encoded),'packSha256':sha((data/'firered.pack').read_bytes()),'cryCatalogSha256':sha((data/'normal-cries.bin').read_bytes()),'coverageSha256':sha((ROOT/'research-integration/render/coverage.json').read_bytes())}
(core/'PROVENANCE.json').write_text(json.dumps(record,indent=2)+'\n')
print(json.dumps({'manifestSha256':sha(encoded),'cueCount':len(cues),'resourceBytes':sum(p.stat().st_size for p in data.iterdir() if p.is_file()),'sourceFiles':len(sourcehashes)},indent=2))
