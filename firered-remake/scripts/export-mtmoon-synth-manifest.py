#!/usr/bin/env python3
"""Export the pinned 170-cue recipe without rendering or copying audio samples."""
import argparse
import hashlib
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
SHA = "1915e4ea554a01bc3071bda853d8cf8baaec2edbab300766672928b6f02811ea"
BYTES = 61166
PRIOR_SHA = "55e4251d31811d072d0c1266083550e7858a8f3104c6f7b18b6102a2888122a1"


def verified_recipe(root=ROOT):
    data = (root / "scripts/synth-mtmoon-cues.json").read_bytes()
    if len(data) != BYTES or hashlib.sha256(data).hexdigest() != SHA:
        raise ValueError("pinned MtMoon synth recipe differs")
    prior_data = (root / "scripts/synth-route3-cues.json").read_bytes()
    if len(prior_data) != 54183 or hashlib.sha256(prior_data).hexdigest() != PRIOR_SHA:
        raise ValueError("pinned prior151 recipe differs")
    prior = json.loads(prior_data)["cues"]
    cues = json.loads(data)["cues"]
    by_id = {cue["id"]: cue for cue in cues}
    if len(cues) != 170 or len(by_id) != 170 or sum(c["sourcePlayer"] == 4 for c in cues) != 56:
        raise ValueError("MtMoon cue inventory differs")
    if len(prior) != 151 or any(by_id.get(cue["id"]) != cue for cue in prior):
        raise ValueError("prior151 cue metadata changed")
    for name, expected in [
        ("firered.pack", "00b3a8376e2a44f1919d4a2573a63cb2873a19b5662df496c4f292c16ad0b46d"),
        ("normal-cries.bin", "623fe59bb7fc0b8d3907dd67bc677a7985037e0086698636f35db82e113d7f2e"),
    ]:
        if hashlib.sha256((root / "content/generated/synth-audio" / name).read_bytes()).hexdigest() != expected:
            raise ValueError("original sample/sequence identity differs")
    return data


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = verified_recipe()
    identity = f'''// Generated by scripts/export-mtmoon-synth-manifest.py from a pinned cue recipe.
internal static class SynthManifestIdentity
{{
    public const string Sha256 = "{SHA}";
    public const int Bytes = {BYTES};
    public const int CueCount = 170;
    public const string SourceCommit = "037335f4c725d7c9aecdac87066f2002b4bd7e14";
}}
'''.encode()
    outputs = {
        ROOT / "content/generated/synth-audio/manifest.json": data,
        ROOT / "src/Game.Godot/SynthManifestIdentity.cs": identity,
    }
    for path, expected in outputs.items():
        if args.check:
            if path.read_bytes() != expected:
                raise ValueError("generated output differs: " + str(path))
        else:
            path.write_bytes(expected)
    print(json.dumps({"passed": True, "cues": 170, "normalCries": 56,
                      "manifestSha256": SHA, "prior151Unchanged": True,
                      "samplePackUnchanged": True}))


if __name__ == "__main__":
    main()
