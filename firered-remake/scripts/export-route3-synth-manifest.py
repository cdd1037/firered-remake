#!/usr/bin/env python3
"""Export the pinned151-cue recipe without rendering or copying audio samples."""
import argparse,hashlib,json,pathlib
ROOT=pathlib.Path(__file__).resolve().parents[1]
SHA='55e4251d31811d072d0c1266083550e7858a8f3104c6f7b18b6102a2888122a1'
p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args()
b=(ROOT/'scripts/synth-route3-cues.json').read_bytes()
if len(b)!=54183 or hashlib.sha256(b).hexdigest()!=SHA:raise ValueError('pinned synth recipe differs')
m=json.loads(b)
if len(m['cues'])!=151 or len({c['id']for c in m['cues']})!=151:raise ValueError('cue inventory differs')
for name,expected in [('firered.pack','00b3a8376e2a44f1919d4a2573a63cb2873a19b5662df496c4f292c16ad0b46d'),('normal-cries.bin','623fe59bb7fc0b8d3907dd67bc677a7985037e0086698636f35db82e113d7f2e')]:
 if hashlib.sha256((ROOT/'content/generated/synth-audio'/name).read_bytes()).hexdigest()!=expected:raise ValueError('original sample/sequence identity differs')
outputs={ROOT/'content/generated/synth-audio/manifest.json':b,ROOT/'src/Game.Godot/SynthManifestIdentity.cs':('''// Generated by scripts/export-route3-synth-manifest.py from a pinned cue recipe.
internal static class SynthManifestIdentity
{
    public const string Sha256 = "%s";
    public const int Bytes = 54183;
    public const int CueCount = 151;
    public const string SourceCommit = "037335f4c725d7c9aecdac87066f2002b4bd7e14";
}
'''%SHA).encode()}
for path,data in outputs.items():
 if a.check:
  if path.read_bytes()!=data:raise ValueError('generated output differs: '+str(path))
 else:path.write_bytes(data)
print(json.dumps({'passed':True,'cues':151,'normalCries':40,'manifestSha256':SHA,'samplePackUnchanged':True}))
