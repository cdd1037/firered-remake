#!/usr/bin/env python3
"""Import all 354 pinned ordinary moves, without granting any execution capability.

Offline by default. --reference reads fixed Git blobs, never runs upstream programs.
--verify authenticates and recomputes all outputs without changing any file.
"""
import argparse
import hashlib
import json
import pathlib
import re
import struct
import subprocess

ROOT = pathlib.Path(__file__).resolve().parents[1]
COMMIT = '037335f4c725d7c9aecdac87066f2002b4bd7e14'
TREE = '7515cd4067ea55f8cdbc73624478afd2736c58b9'
PROFILE = 'firered-metronome-metadata-v1'
LOCK_PATH = 'content/sources/metronome-moves/source-lock.json'
LOCK_SHA = '449c78972943f57e680843b44e45d7e06509037b82d20149b706e2483ef2b747'
OUTPUT_PATH = 'content/generated/metronome-moves/catalog.json'
# These independent output pins change only with a reviewed source/importer change.
CATALOG_SHA = 'dd93a57abc65c8c313647c5dd78666551e716e97e1ea807f3d9a84485a57c54d'
MANIFEST_SHA = '0c60a21bc58f72d278b3f999d0fea97fab50b731363a162f25a677e80bcfd6d3'
VALIDATOR_PATH = 'src/Game.Domain/WildBattle/MetronomeSourceMoveDefinition.cs'
VALIDATOR_SHA = '2bd9a8d78cfa9f20d00dbffe4f61e9ec06e8e3e581256a8d999e7fd9a65dcd26'


def sha(data):
    return hashlib.sha256(data).hexdigest()


def canonical(value):
    return (json.dumps(value, sort_keys=True, separators=(',', ':'), ensure_ascii=False) + '\n').encode()


def safe(root, relative):
    if pathlib.PurePosixPath(relative).is_absolute() or '\\' in relative or any(p in ('', '.', '..') for p in relative.split('/')):
        raise ValueError('Unsafe relative path: ' + relative)
    path = pathlib.Path(root).absolute() / relative
    if any(p.is_symlink() for p in (path, *path.parents)):
        raise ValueError('Symlink rejected: ' + relative)
    return path


def authenticate(root, reference=None):
    lock_bytes = safe(root, LOCK_PATH).read_bytes()
    if sha(lock_bytes) != LOCK_SHA:
        raise ValueError('Metronome source lock differs')
    lock = json.loads(lock_bytes)
    if (lock['commit'], lock['tree'], lock['profile'], len(lock['files'])) != (COMMIT, TREE, PROFILE, 11):
        raise ValueError('Metronome source identity differs')
    if reference and subprocess.check_output(['git', '-C', str(reference), 'rev-parse', 'HEAD']).decode().strip() != COMMIT:
        raise ValueError('Reference HEAD differs')
    raw = {}
    for row in lock['files']:
        path = safe(root, 'content/raw/metronome-moves/' + row['path'])
        data = subprocess.check_output(['git', '-C', str(reference), 'show', COMMIT + ':' + row['path']]) if reference else path.read_bytes()
        if (len(data), sha(data), hashlib.sha1(f'blob {len(data)}\0'.encode() + data).hexdigest()) != (row['byteLength'], row['sha256'], row['gitBlobSha1']):
            raise ValueError('Metronome source bytes differ: ' + row['path'])
        raw[row['path']] = data
    return lock, raw


def definition_fingerprint(move):
    """Length-framed UTF-8 + signed little-endian int32; bool is exactly one byte."""
    data = bytearray()

    def integer(value):
        data.extend(struct.pack('<i', value))

    def string(value):
        encoded = value.encode('utf-8')
        integer(len(encoded))
        data.extend(encoded)

    string('firered-source-move-definition-v1')
    string(COMMIT)
    string(move['id']['value'])
    integer(move['sourceMoveId'])
    integer(move['pp'])
    integer(move['power'])
    string(move['type'])
    integer(move['accuracy'])
    string(move['effect'])
    integer(move['secondaryEffectChance'])
    string(move['target'])
    integer(move['priority'])
    integer(len(move['flags']))
    for flag in move['flags']:
        string(flag)
    data.append(1 if move['battleEffectImplemented'] else 0)
    string(move['source']['path'])
    string(move['source']['symbol'])
    integer(move['source']['startLine'])
    integer(move['source']['endLine'])
    string(move['source']['sha256'])
    return sha(data)


def domain_validator(moves):
    rows = '\n'.join('        "' + definition_fingerprint(m) + '", // ' + str(m['sourceMoveId']) for m in moves)
    return ('''// Generated by scripts/import-metronome-move-catalog.py from authenticated source.
// Metadata authentication only. No battle handler or scope is registered here.
using System.Security.Cryptography;
using System.Text;
using Game.Domain.Pokemon;

namespace Game.Domain.WildBattle;

/// <summary>Authenticates every field, ordered flag and provenance against 354 pinned source definitions.</summary>
public static class MetronomeSourceMoveDefinition
{
    public const string SourceCommit = "''' + COMMIT + '''";
    public const int OrdinaryMoveCount = 354;

    public static bool Matches(PokemonMoveDefinition? move)
    {
        if (move is null || move.Source is null || move.SourceMoveId is < 1 or > OrdinaryMoveCount ||
            move.Flags.IsDefault || move.Flags.Length > 6 || move.BattleEffectImplemented ||
            !Text(move.Id.Value) || !Text(move.Type) || !Text(move.Effect) || !Text(move.Target) ||
            !Text(move.Source.Path) || !Text(move.Source.Symbol) || !Text(move.Source.Sha256) ||
            move.Flags.Any(flag => !Text(flag))) return false;
        using var stream = new MemoryStream();
        using var writer = new BinaryWriter(stream, Encoding.UTF8, leaveOpen: true);
        void String(string value)
        {
            byte[] bytes = Encoding.UTF8.GetBytes(value);
            writer.Write(bytes.Length);
            writer.Write(bytes);
        }
        String("firered-source-move-definition-v1");
        String(SourceCommit);
        String(move.Id.Value);
        writer.Write(move.SourceMoveId);
        writer.Write(move.Pp);
        writer.Write(move.Power);
        String(move.Type);
        writer.Write(move.Accuracy);
        String(move.Effect);
        writer.Write(move.SecondaryEffectChance);
        String(move.Target);
        writer.Write(move.Priority);
        writer.Write(move.Flags.Length);
        foreach (string flag in move.Flags) String(flag);
        writer.Write(move.BattleEffectImplemented);
        String(move.Source.Path);
        String(move.Source.Symbol);
        writer.Write(move.Source.StartLine);
        writer.Write(move.Source.EndLine);
        String(move.Source.Sha256);
        writer.Flush();
        return Convert.ToHexStringLower(SHA256.HashData(stream.GetBuffer().AsSpan(0, checked((int)stream.Length)))) ==
            Fingerprints[move.SourceMoveId - 1];
    }

    // Every authenticated field is ASCII. Reject malformed or unbounded input before allocation.
    private static bool Text(string? value) => value is { Length: > 0 and <= 128 } && value.All(c => c is >= ' ' and <= '~');

    private static readonly string[] Fingerprints =
    [
''' + rows + '''
    ];
}
''').encode('utf-8')


def generate(lock, raw):
    text = {p: b.decode('utf-8') for p, b in raw.items()}
    inventory = {r['path']: r for r in lock['files']}

    def one(path, pattern):
        matches = list(re.finditer(pattern, text[path], re.M | re.S))
        if len(matches) != 1:
            raise ValueError(f'Expected one source match ({len(matches)}): {path}: {pattern}')
        return matches[0]

    def source(path, symbol, match):
        return dict(path=path, symbol=symbol, startLine=text[path].count('\n', 0, match.start()) + 1,
                    endLine=text[path].count('\n', 0, match.end()) + 1, sha256=inventory[path]['sha256'])

    def ident(symbol):
        return dict(value='pret:' + symbol)

    def table(path, symbol):
        return one(path, r'^static const u(?:8|16) ' + symbol + r'\[\] =\s*\n\{\n(.*?)^\};')

    def function(path, symbol):
        return one(path, r'^(?:static )?(?:void|bool8|u8|u16) ' + symbol + r'\([^;\n]*\)\n\{\n.*?^\}')

    constants = []
    specs = [('include/constants/moves.h', 'MOVE_'), ('include/constants/pokemon.h', 'TYPE_'),
             ('include/constants/pokemon.h', 'FLAG_'), ('include/constants/battle_move_effects.h', 'EFFECT_'),
             ('include/constants/abilities.h', 'ABILITY_'), ('include/battle.h', 'MOVE_TARGET_'),
             ('include/constants/battle.h', 'BATTLE_TERRAIN_')]
    for path, prefix in specs:
        for match in re.finditer(r'^#define (' + prefix + r'\w+)[ \t]+([^\n]+)', text[path], re.M):
            symbol, expression = match[1], match[2].split('//')[0].strip()
            shift = re.fullmatch(r'\(1 << (\d+)\)', expression)
            if shift:
                value = 1 << int(shift[1])
            elif re.fullmatch(r'(?:0x[0-9A-Fa-f]+|\d+)', expression):
                value = int(expression, 0) if expression.startswith('0x') else int(expression)
            else:
                raise ValueError('Unsupported constant syntax: ' + symbol + '=' + expression)
            constants.append(dict(symbol=symbol, value=value, source=source(path, symbol, match)))
    constants.sort(key=lambda row: row['symbol'])
    numbers = {c['symbol']: c['value'] for c in constants}
    if len(numbers) != len(constants):
        raise ValueError('Duplicate source constant')
    move_ids = {s: v for s, v in numbers.items() if s.startswith('MOVE_') and not s.startswith('MOVE_TARGET_')}
    if move_ids.pop('MOVE_UNAVAILABLE') != 65535 or sorted(move_ids.values()) != list(range(355)):
        raise ValueError('Ordinary source move ID closure differs')

    moves = []
    move_names = []
    path = 'src/data/battle_moves.h'
    fields = {'effect', 'power', 'type', 'accuracy', 'pp', 'secondaryEffectChance', 'target', 'priority', 'flags'}
    blocks = list(re.finditer(r'^    \[(MOVE_\w+)\] =\s*\n    \{\n(.*?)^    \},', text[path], re.M | re.S))
    if len(blocks) != 355 or len({b[1] for b in blocks}) != 355:
        raise ValueError('Source move table scope differs')
    for match in blocks:
        symbol = match[1]
        pairs = re.findall(r'^\s*\.(\w+) = (.+),$', match[2], re.M)
        values = dict(pairs)
        if len(pairs) != len(fields) or set(values) != fields:
            raise ValueError('Unknown or duplicate move fields: ' + symbol)
        if symbol == 'MOVE_NONE':
            continue
        flags = [] if values['flags'] == '0' else values['flags'].split(' | ')
        if len(set(flags)) != len(flags) or any(not f.startswith('FLAG_') or f not in numbers for f in flags):
            raise ValueError('Unsupported source flags: ' + symbol)
        for field, prefix in [('effect', 'EFFECT_'), ('type', 'TYPE_'), ('target', 'MOVE_TARGET_')]:
            if not values[field].startswith(prefix) or values[field] not in numbers:
                raise ValueError('Unsupported move constant: ' + symbol + ':' + field)
        moves.append(dict(id=ident(symbol), sourceMoveId=move_ids[symbol], pp=int(values['pp']), power=int(values['power']),
                          type=values['type'], accuracy=int(values['accuracy']), effect=values['effect'],
                          secondaryEffectChance=int(values['secondaryEffectChance']), target=values['target'],
                          priority=int(values['priority']), flags=flags, battleEffectImplemented=False,
                          source=source(path, symbol, match)))
        name_path = 'src/data/text/move_names.h'
        name_match = one(name_path, r'^    \[' + symbol + r'\]\s*= _\("([^"\n]+)"\),?$')
        move_names.append(dict(id=ident(symbol), name=name_match[1], source=source(name_path, symbol, name_match)))
    moves.sort(key=lambda m: m['sourceMoveId'])
    move_names.sort(key=lambda m: move_ids[m['id']['value'][5:]])
    if [m['sourceMoveId'] for m in moves] != list(range(1, 355)):
        raise ValueError('Missing or duplicate ordinary move')

    commands = 'src/battle_script_commands.c'
    util = 'src/battle_util.c'
    forbidden_match = table(commands, 'sMovesForbiddenToCopy')
    forbidden_tokens = re.findall(r'^    (\w+),?$', forbidden_match[1], re.M)
    if forbidden_tokens[4] != 'MIMIC_FORBIDDEN_END' or forbidden_tokens[-1] != 'METRONOME_FORBIDDEN_END' or len(forbidden_tokens) != 20:
        raise ValueError('Caller delimiter policy differs')
    forbidden = [token for token in forbidden_tokens if token.startswith('MOVE_')]
    direct = [m['id'] for m in moves if m['id']['value'][5:] not in forbidden]
    extras = [m['id'] for m in moves if m['id']['value'][5:] in forbidden and 'FLAG_MIRROR_MOVE_AFFECTED' in m['flags']]
    sound_match = table(util, 'sSoundMovesTable')
    sound = re.findall(r'\bMOVE_\w+\b', sound_match[1])
    critical_match = function(commands, 'Cmd_critcalc')
    critical = re.findall(r'gBattleMoves\[gCurrentMove\].effect == (EFFECT_\w+)', critical_match[0])
    invalid_match = function(commands, 'IsInvalidForSleepTalkOrAssist')
    invalid = re.findall(r'move == (MOVE_\w+)', invalid_match[0])
    nature_match = table(commands, 'sNaturePowerMoves')
    nature = [dict(terrain=t, move=ident(m)) for t, m in re.findall(r'\[(BATTLE_TERRAIN_\w+)\]\s*= (MOVE_\w+)', nature_match[1])]
    if (len(direct), len(extras), len(sound), len(critical), len(nature)) != (336, 6, 10, 4, 10):
        raise ValueError('Source caller/ability policies differ')
    dispatch = []
    scripts = 'data/battle_scripts_1.s'
    for match in re.finditer(r'^[ \t]*\.4byte (\w+)[ \t]+@ (EFFECT_\w+)[ \t]*$', text[scripts], re.M):
        label_match = one(scripts, r'^' + match[1] + r':{1,2}[ \t]*$')
        dispatch.append(dict(effect=match[2], scriptLabel=match[1], source=source(scripts, match[2], match),
                             scriptSource=source(scripts, match[1], label_match)))
    if len({d['effect'] for d in dispatch}) != len(dispatch) or any(m['effect'] not in {d['effect'] for d in dispatch} for m in moves):
        raise ValueError('Effect dispatch table incomplete')

    ability_policies = []
    for path, symbol in [(util, 'AbilityBattleEffects'), (util, 'GetMoveTarget'), (commands, 'Cmd_ppreduce'),
                         (commands, 'Cmd_critcalc'), (commands, 'SetMoveEffect'),
                         (commands, 'Cmd_seteffectwithchance'), (commands, 'Cmd_healpartystatus')]:
        match = function(path, symbol)
        abilities = sorted(set(re.findall(r'\bABILITY_\w+\b', match[0])))
        if any(a not in numbers for a in abilities):
            raise ValueError('Unknown source ability')
        ability_policies.append(dict(symbol=symbol, abilities=abilities, source=source(path, symbol, match)))
    policies = dict(metronomeForbiddenMoves=[ident(m) for m in forbidden], directCallableMoves=direct,
                    mirrorMoveExtraResults=extras, mimicForbiddenMoves=[ident(m) for m in forbidden_tokens[:4]],
                    invalidSleepTalkOrAssistMoves=[ident(m) for m in invalid], soundMoves=[ident(m) for m in sound],
                    highCriticalEffects=critical, naturePowerMoves=nature, effectDispatch=dispatch,
                    abilityPolicies=ability_policies,
                    sourceReferences=[source(commands, 'sMovesForbiddenToCopy', forbidden_match),
                                      source(util, 'sSoundMovesTable', sound_match),
                                      source(commands, 'Cmd_critcalc', critical_match),
                                      source(commands, 'IsInvalidForSleepTalkOrAssist', invalid_match),
                                      source(commands, 'sNaturePowerMoves', nature_match)])
    document = dict(schemaVersion=1, profile=PROFILE, sourceCommit=COMMIT, inputs=lock['files'],
                    moves=moves, moveNames=move_names, constants=constants, policies=policies)
    catalog = canonical(document)
    manifest = canonical(dict(schemaVersion=1, profile=PROFILE, sourceCommit=COMMIT, tree=TREE,
                              lockSha256=LOCK_SHA, inputCount=len(raw), ordinaryMoveCount=len(moves),
                              directCallableMoveCount=len(direct), mirrorExtraMoveCount=len(extras),
                              outputs=[dict(path='catalog.json', byteLength=len(catalog), sha256=sha(catalog))]))
    return {OUTPUT_PATH: catalog, 'content/generated/metronome-moves/manifest.json': manifest,
            VALIDATOR_PATH: domain_validator(moves)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--project-root', type=pathlib.Path, default=ROOT)
    parser.add_argument('--reference', type=pathlib.Path)
    parser.add_argument('--verify', action='store_true')
    args = parser.parse_args()
    if args.verify and args.reference:
        parser.error('--verify is read-only; reseed with --reference separately')
    lock, raw = authenticate(args.project_root, args.reference)
    outputs = generate(lock, raw)
    for path, expected in [(OUTPUT_PATH, CATALOG_SHA), ('content/generated/metronome-moves/manifest.json', MANIFEST_SHA),
                           (VALIDATOR_PATH, VALIDATOR_SHA)]:
        if sha(outputs[path]) != expected:
            raise ValueError('Generated Metronome bytes differ from reviewed pin: ' + path)
    if args.verify:
        for path, data in outputs.items():
            if safe(args.project_root, path).read_bytes() != data:
                raise ValueError('Generated Metronome output differs: ' + path)
    else:
        if args.reference:
            for path, data in raw.items():
                target = safe(args.project_root, 'content/raw/metronome-moves/' + path)
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(data)
        for path, data in outputs.items():
            target = safe(args.project_root, path)
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)
    print(json.dumps(dict(verified=args.verify, ordinaryMoves=354, directCallable=336, mirrorExtras=6,
                          effectExecutionGranted=False, outputs={p: dict(byteLength=len(b), sha256=sha(b)) for p, b in outputs.items()}), sort_keys=True))


if __name__ == '__main__':
    main()
