using System.Collections.Immutable;
using System.Globalization;
using System.Security.Cryptography;
using System.Text;
using Game.Domain.Items;

namespace Game.Content;

public sealed record PretOpeningItemInput(string Path, int ByteLength, string GitBlobSha1, string Sha256);
public sealed record PretOpeningItemsDocument(int SchemaVersion, ImmutableArray<PretOpeningItemInput> Inputs,
    ImmutableArray<OpeningItemSourceRef> RulesSources, ImmutableArray<string> Limitations, OpeningItemsCatalog Catalog);

/// <summary>Validates the complete reviewed UTF-8 artifact; the caller owns filesystem access.</summary>
public static class PretOpeningItems
{
    public const string GeneratedSha256 = "6785faa588b7e4d9b2a1c728c65efd950ffc03145f459730ef0679579f050aea";
    public const string SourceManifestSha256 = "7611f3a45fee61e01e848b954982f2855e65ee90d524554ad57af04ae2864eb7";

    public static OpeningItemsCatalog Load(string generatedJson)
    {
        var document = ContentJson.ParseStrict<PretOpeningItemsDocument>(generatedJson, ContentJson.CreateOptions());
        if (document.SchemaVersion != 1 || document.Inputs.IsDefault || document.Inputs.Length != 17 ||
            document.RulesSources.IsDefaultOrEmpty || document.Limitations.IsDefaultOrEmpty || document.Catalog is null)
            throw ContentJson.Error("opening_items_profile", "$", "The complete bounded Potion document is required.");
        var inputs = new Dictionary<string, PretOpeningItemInput>(StringComparer.Ordinal);
        foreach (var input in document.Inputs)
            if (input is null || string.IsNullOrWhiteSpace(input.Path) || input.ByteLength <= 0 ||
                input.Sha256 is null || input.GitBlobSha1 is null || !inputs.TryAdd(input.Path, input))
                throw ContentJson.Error("opening_items_inputs", "$.inputs", "Invalid or duplicate source identity.");
        string manifest = string.Concat(inputs.Values.OrderBy(x => x.Path, StringComparer.Ordinal).Select(x =>
            x.Path + "|" + x.ByteLength.ToString(CultureInfo.InvariantCulture) + "|" + x.GitBlobSha1 + "|" + x.Sha256 + "\n"));
        if (Hash(manifest) != SourceManifestSha256)
            throw ContentJson.Error("opening_items_source_hash", "$.inputs", "Source manifest differs from the fixed Git blobs and SHA-256 identities.");
        void Source(OpeningItemSourceRef source)
        {
            if (source is null || source.Path is null || string.IsNullOrWhiteSpace(source.Symbol) ||
                source.StartLine < 1 || source.EndLine < source.StartLine ||
                !inputs.TryGetValue(source.Path, out var input) || input.Sha256 != source.Sha256)
                throw ContentJson.Error("opening_items_source_ref", "$", "Invalid source line, symbol or byte identity.");
        }
        try { OpeningInventoryRules.ValidateCatalog(document.Catalog); }
        catch (ArgumentException ex) { throw ContentJson.Error("opening_items_catalog", "$.catalog", ex.Message); }
        catch (NotSupportedException ex) { throw ContentJson.Error("opening_items_catalog", "$.catalog", ex.Message); }
        Source(document.Catalog.Potion.Source);
        Source(document.Catalog.Potion.EffectSource);
        foreach (var source in document.RulesSources) Source(source);
        if (Hash(generatedJson) != GeneratedSha256)
            throw ContentJson.Error("opening_items_generated_hash", "$", "Generated bytes differ from the reviewed deterministic Potion artifact.");
        return document.Catalog;
    }

    private static string Hash(string value) => Convert.ToHexStringLower(SHA256.HashData(Encoding.UTF8.GetBytes(value)));
}
