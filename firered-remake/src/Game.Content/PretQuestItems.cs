using System.Collections.Immutable;
using System.Globalization;
using System.Security.Cryptography;
using System.Text;
using Game.Domain.Items;

namespace Game.Content;

public sealed record PretQuestItemInput(string Path, int ByteLength, string GitBlobSha1, string Sha256);
public sealed record PretQuestItemsDocument(int SchemaVersion, ImmutableArray<PretQuestItemInput> Inputs,
    ImmutableArray<OpeningItemSourceRef> RulesSources, ImmutableArray<string> Limitations, QuestItemsCatalog Catalog);

/// <summary>Loads only the complete, byte-pinned local Parcel/Poke Ball source artifact.</summary>
public static class PretQuestItems
{
    public const string GeneratedSha256 = "5e772267027549fbab4cac7e79581aad926776f1f0efe693af22886dcbabb00a";
    public const string SourceManifestSha256 = "0d7e281d859a0d43db8e68ba45bb3b715e1bd766a21243a0d329384d3bddf2c1";

    public static QuestItemsCatalog Load(string generatedJson)
    {
        var document = ContentJson.ParseStrict<PretQuestItemsDocument>(generatedJson, ContentJson.CreateOptions());
        if (document.SchemaVersion != 1 || document.Inputs.IsDefault || document.Inputs.Length != 12 ||
            document.RulesSources.IsDefaultOrEmpty || document.Limitations.IsDefaultOrEmpty || document.Catalog is null)
            throw ContentJson.Error("quest_items_profile", "$", "The complete bounded Parcel/Poke Ball document is required.");
        var inputs = new Dictionary<string, PretQuestItemInput>(StringComparer.Ordinal);
        foreach (var input in document.Inputs)
            if (input is null || string.IsNullOrWhiteSpace(input.Path) || input.ByteLength <= 0 ||
                input.Sha256 is null || input.GitBlobSha1 is null || !inputs.TryAdd(input.Path, input))
                throw ContentJson.Error("quest_items_inputs", "$.inputs", "Invalid or duplicate source identity.");
        string manifest = string.Concat(inputs.Values.OrderBy(x => x.Path, StringComparer.Ordinal).Select(x =>
            x.Path + "|" + x.ByteLength.ToString(CultureInfo.InvariantCulture) + "|" + x.GitBlobSha1 + "|" + x.Sha256 + "\n"));
        if (Hash(manifest) != SourceManifestSha256)
            throw ContentJson.Error("quest_items_source_hash", "$.inputs", "Source manifest differs from the fixed Git blobs and SHA-256 identities.");
        void Source(OpeningItemSourceRef source)
        {
            if (source is null || source.Path is null || string.IsNullOrWhiteSpace(source.Symbol) ||
                source.StartLine < 1 || source.EndLine < source.StartLine ||
                !inputs.TryGetValue(source.Path, out var input) || input.Sha256 != source.Sha256)
                throw ContentJson.Error("quest_items_source_ref", "$", "Invalid source line, symbol or byte identity.");
        }
        try { QuestItemRules.ValidateCatalog(document.Catalog); }
        catch (ArgumentException ex) { throw ContentJson.Error("quest_items_catalog", "$.catalog", ex.Message); }
        catch (NotSupportedException ex) { throw ContentJson.Error("quest_items_catalog", "$.catalog", ex.Message); }
        foreach (var item in document.Catalog.Items) Source(item.Source);
        foreach (var source in document.RulesSources) Source(source);
        if (Hash(generatedJson) != GeneratedSha256)
            throw ContentJson.Error("quest_items_generated_hash", "$", "Generated bytes differ from the reviewed deterministic Parcel/Poke Ball artifact.");
        return document.Catalog;
    }

    private static string Hash(string value) => Convert.ToHexStringLower(SHA256.HashData(Encoding.UTF8.GetBytes(value)));
}
