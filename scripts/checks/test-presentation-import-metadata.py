#!/usr/bin/env python3
"""Regenerate exact presentation bytes from retained inputs, without stage inventories."""
import sys as _bootstrap_sys
from pathlib import Path as _BootstrapPath
_bootstrap_sys.path.insert(0, str(_BootstrapPath(__file__).resolve().parents[2] / 'scripts/lib'))
from project_paths import PROJECT_ROOT as _PROJECT_ROOT

import json
import io
import tempfile
from PIL import Image
from generated_output_compare import generated_output_matches
from presentation_output import asset_emitter, publish
from pathlib import Path
import runpy
import unittest

ROOT = _PROJECT_ROOT
PACKAGES = ('celio', 'four-island', 'five-island', 'six-island', 'seven-island',
            'sevii-ruby', 'event-island', 'mewtwo', 'league-rematch')
INVENTORIES = {'inputs', 'inheritedInputs', 'sourcePaths', 'sourceFiles', 'localInputs', 'dependencyInputs'}


class PresentationImportMetadataTests(unittest.TestCase):
    def test_asset_emission_preserves_order_pixels_and_inheritance(self):
        pixels = bytes((13, 27, 41, 0)) * 6
        image = Image.frombytes('RGBA', (2, 3), pixels)
        encoded = io.BytesIO(); image.save(encoded, format='PNG')
        class Source:
            def reuse(self, path):
                self.path = path
                return encoded.getvalue()
        source, output, assets = Source(), {}, []
        emit = asset_emitter(source, output, assets, 'sprites/', {'old': 'existing.png'})
        first = emit('new', 2, 3, pixels, ['source.png'])
        inherited = emit('old', 2, 3, pixels, [])
        self.assertEqual(assets, [first, inherited])
        self.assertEqual(first, dict(id='new', width=2, height=3, texturePath='sprites/new.png'))
        self.assertEqual(inherited, dict(id='old', width=2, height=3, texturePath='existing.png', inherited=True))
        self.assertEqual(source.path, 'existing.png')
        self.assertEqual(list(output), ['new.png'])
        self.assertEqual(Image.open(io.BytesIO(output['new.png'])).convert('RGBA').tobytes(), pixels)
        for identity, bad_pixels, error in [('bad', pixels[:-1], 'RGBA dimensions differ'),
                                             ('old', bytes(len(pixels)), 'Inherited asset source pixels differ: old')]:
            with self.assertRaisesRegex(ValueError, error):
                emit(identity, 2, 3, bad_pixels, [])
        self.assertEqual(assets, [first, inherited])
        self.assertEqual(list(output), ['new.png'])

    def test_publish_keeps_strict_check_and_sequential_path_guards(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            output = {'nested/a.json': b'{"x":1}', 'b.bin': b'bytes'}
            publish(root, output, check=False)
            def snapshot():
                return {str(p): (p.read_bytes(), p.stat().st_mtime_ns)
                        for p in root.rglob('*') if p.is_file()}
            before = snapshot()
            publish(root, output, check=True)
            self.assertEqual(snapshot(), before)
            with self.assertRaisesRegex(ValueError, 'Generated bytes differ: nested/a.json'):
                publish(root, {'nested/a.json': b'{ "x": 1 }'}, check=True)
            with self.assertRaises(FileNotFoundError):
                publish(root, {'missing/file': b'new'}, check=True)
            self.assertEqual(snapshot(), before)
            self.assertFalse((root / 'missing').exists())
            with self.assertRaisesRegex(ValueError, 'Unsafe presentation path'):
                publish(root, {'first': b'written first', '../escape': b'bad'}, check=False)
            self.assertEqual((root / 'first').read_bytes(), b'written first')
            (root / 'link').symlink_to(root / 'nested', target_is_directory=True)
            with self.assertRaisesRegex(ValueError, 'Presentation symlink rejected'):
                publish(root, {'link/a.json': b'changed'}, check=False)
            self.assertEqual((root / 'nested/a.json').read_bytes(), output['nested/a.json'])

    def test_generated_comparison_ignores_only_serialization(self):
        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory) / 'data.json'
            path.write_bytes(b'{"a":1,"b":[true,2]}')
            self.assertTrue(generated_output_matches(path, b'{ "b": [true, 2], "a": 1 }'))
            self.assertFalse(generated_output_matches(path, b'{"a":1,"b":[1,2]}'))
            self.assertFalse(generated_output_matches(path, b'{"a":1,"b":[2,true]}'))
            self.assertFalse(generated_output_matches(path, b'{"a":1}'))
            image = Image.new('RGBA', (2, 3), (12, 34, 56, 0))
            path = Path(directory) / 'image.png'
            image.save(path, compress_level=0)
            encoded = io.BytesIO(); image.save(encoded, format='PNG', compress_level=9)
            self.assertTrue(generated_output_matches(path, encoded.getvalue()))
            image.putpixel((0, 0), (13, 34, 56, 0))
            encoded = io.BytesIO(); image.save(encoded, format='PNG')
            self.assertFalse(generated_output_matches(path, encoded.getvalue()))
            encoded = io.BytesIO(); Image.new('RGBA', (3, 2)).save(encoded, format='PNG')
            self.assertFalse(generated_output_matches(path, encoded.getvalue()))
            path = Path(directory) / 'audio.bin'; path.write_bytes(b'abc')
            self.assertTrue(generated_output_matches(path, b'abc'))
            self.assertFalse(generated_output_matches(path, b'abd'))

    def test_real_writers_reproduce_runtime_bytes_without_stage_inventories(self):
        for package in PACKAGES:
            with self.subTest(package=package):
                module = runpy.run_path(str(ROOT / f'scripts/imports/presentation/import-{package}-presentation.py'))
                args = (ROOT, None) if package in ('four-island', 'sevii-ruby') else (ROOT, None, ROOT)
                outputs, _ = module['build'](*args)
                runtime_count = 0
                for path, data in outputs.items():
                    if path.startswith('content/generated/'):
                        runtime_count += 1
                        self.assertEqual((ROOT / path).read_bytes(), data, path)
                        if path.endswith('.json'):
                            self.assert_runtime_fields(json.loads(data), path)
                self.assertGreater(runtime_count, 0)
                self.assertFalse(any(path.startswith('scripts/recipes/') for path in outputs))
                self.assertTrue(any(path.startswith('content/raw/') for path in outputs))

    def assert_runtime_fields(self, value, path):
        if isinstance(value, dict):
            for key, item in value.items():
                self.assertFalse(key in INVENTORIES and isinstance(item, list), f'{path}: {key}')
                self.assertNotEqual(key, 'decodedSha256', path)
                self.assert_runtime_fields(item, path)
        elif isinstance(value, list):
            for item in value:
                self.assert_runtime_fields(item, path)


if __name__ == '__main__':
    unittest.main()
