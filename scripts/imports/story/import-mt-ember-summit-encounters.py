#!/usr/bin/env python3
"""Project the three pinned FireRed summit-path land tables into shared Domain rows."""
import argparse
import json
from pathlib import Path
import re
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[3] / 'scripts/lib'))
from pokemon_import_io import read_source, safe, unique_pairs, write_files
from project_paths import PROJECT_ROOT

COMMIT = '037335f4c725d7c9aecdac87066f2002b4bd7e14'
WILD = 'src/data/wild_encounters.json'
OUTPUT = 'src/Game.Domain/Encounters/MtEmberSummitEncounterTables.cs'
MAPS = tuple((f'MAP_MT_EMBER_SUMMIT_PATH_{floor}F', f'sMtEmberSummitPath{floor}F_FireRed',
              f'map.mt-ember-summit-path-{floor}f') for floor in (1, 2, 3))


def exactly_one(values, description):
    if len(values) != 1:
        raise ValueError('Expected one ' + description)
    return values[0]


def convert(source):
    wild = json.loads(source, object_pairs_hook=unique_pairs)
    lines = ['// Generated by scripts/imports/story/import-mt-ember-summit-encounters.py from pinned FireRed rows.',
             'using System.Collections.Immutable;', '', 'namespace Game.Domain.Encounters;', '',
             'public static class MtEmberSummitEncounterTables', '{',
             '    public static ImmutableArray<EarlyLandEncounterTable> Land { get; } = [']
    for symbol, label, map_id in MAPS:
        group, row = exactly_one([(group, row) for group in wild['wild_encounter_groups']
                                 if group.get('for_maps') is True for row in group.get('encounters', [])
                                 if row.get('map') == symbol and row.get('base_label') == label],
                                symbol + ' FireRed table')
        weights = exactly_one([field['encounter_rates'] for field in group['fields']
                               if field['type'] == 'land_mons'], 'land slot weights')
        land = row['land_mons']
        if len(weights) != 12 or len(land['mons']) != len(weights):
            raise ValueError('Land slots and weights must have twelve entries')
        if any(type(weight) is not int or weight <= 0 for weight in weights) or sum(weights) != 100:
            raise ValueError('Invalid land slot weights')
        rate = land['encounter_rate']
        if type(rate) is not int or not 0 < rate <= 255:
            raise ValueError('Invalid land encounter rate')
        lines.append(f'        new(new("{map_id}"), {rate}, [')
        for index, (mon, weight) in enumerate(zip(land['mons'], weights)):
            species, low, high = mon['species'], mon['min_level'], mon['max_level']
            if not isinstance(species, str) or not re.fullmatch(r'SPECIES_[A-Z0-9_]+', species):
                raise ValueError('Invalid encounter species')
            if type(low) is not int or type(high) is not int or not 1 <= low <= high <= 100:
                raise ValueError('Invalid encounter levels')
            lines.append(f'            new({index}, new("pret:{species}"), {low}, {high}, {weight}),')
        lines.append('        ]),')
    lines.extend(['    ];', '}'])
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--raw-root', type=Path, default=PROJECT_ROOT / 'content/raw/pokefirered/037335f4')
    parser.add_argument('--project-root', type=Path, default=PROJECT_ROOT)
    parser.add_argument('--reference-root', type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    source = read_source(args.raw_root, WILD, commit=COMMIT, repository=args.reference_root)
    result = convert(source)
    destination = safe(args.project_root, OUTPUT)
    raw = safe(args.raw_root)
    if destination == raw or destination.is_relative_to(raw):
        raise ValueError('Output must not overlap raw inputs')
    if args.check:
        if destination.read_text(encoding='utf-8') != result:
            raise ValueError('Generated summit land tables differ: ' + str(destination))
    else:
        write_files(args.project_root, {OUTPUT: result.encode('utf-8')})
    print(json.dumps(dict(checked=args.check, landTables=len(MAPS), landSlots=12 * len(MAPS), output=OUTPUT)))


if __name__ == '__main__':
    main()
